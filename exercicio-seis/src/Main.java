/*Este exercicio tem como objetivo criar um programa que calcule
a = 7
b = 3
E que faça a soma, subtração e multiplicação
 */

public class Main{
    public static void main(String[] args){

        int a = 7;
        int b = 3;

        int soma = (a + b);
        int subtracao = (a - b);
        int multiplicacao = (a * b);

        System.out.println(soma);
        System.out.println(subtracao);
        System.out.println(multiplicacao);
    }
}